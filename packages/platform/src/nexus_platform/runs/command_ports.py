"""Write-side persistence and authorization contracts used by Run application services.

Every adapter is bound to the same UnitOfWork. Methods never commit independently;
owner-scoped reads lock before returning independent application objects.
"""
from datetime import datetime
from typing import Any, Protocol
from uuid import UUID

from nexus_core.platform import Principal
from .configuration import (
    AuthorizedMember, BoundResource, PublishedAgent, PublishedModel, SubmissionSession,
)
from .domain import Delivery, PendingInput, Run
from .ports import OutboxRepository, RunRepository, RunUnitOfWork, TenantAccess


class RunWriteRepository(RunRepository, Protocol):
    def for_delivery(self, delivery: Delivery) -> Run | None:
        """Internal worker load under the Run lock, after checking this locked delivery's owner."""
        ...
    def owned_for_update(self, tenant_id: UUID, user_id: UUID, run_id: UUID) -> Run | None: ...
    def by_key(self, tenant_id: UUID, user_id: UUID, key: str) -> Run | None: ...
    def has_active(self, session_id: UUID) -> bool: ...
    def insert_or_replay(self, run: Run) -> tuple[Run, bool]:
        """Return (persisted state, inserted); use a savepoint for uniqueness races.

        Unrelated integrity failures propagate. A conflicting existing request is returned
        for the application to check its hash; the adapter does not decide replay policy.
        """
        ...
    def save(self, run: Run) -> None: ...


class SubmissionCatalog(Protocol):
    def owned_session(self, tenant_id: UUID, user_id: UUID, session_id: UUID) -> SubmissionSession | None: ...
    def agent_version(self, version_id: UUID) -> PublishedAgent | None: ...
    def agent_tenant(self, agent_id: UUID) -> UUID | None: ...
    def bindings(self, version_id: UUID) -> list[BoundResource]: ...
    def model_version(self, version_id: UUID) -> PublishedModel | None: ...
    def model_tenant(self, profile_id: UUID) -> UUID | None: ...
    def touch_session(self, session_id: UUID, at: datetime) -> None: ...


class SubmissionAccess(TenantAccess, Protocol):
    def require_member(self, principal: Principal, tenant_id: UUID) -> AuthorizedMember: ...
    def require_resource(self, tenant_id: UUID, binding: BoundResource) -> None: ...
    def require_model(self, tenant_id: UUID, user_id: UUID, version_id: UUID) -> None: ...
    def require_agent_run(self, tenant_id: UUID, user_id: UUID, agent_id: UUID) -> None: ...


class RunQueueRepository(OutboxRepository, Protocol):
    def lock_delivery(self, task_id: UUID) -> Delivery | None: ...
    def complete_delivery(self, task_id: UUID, at: datetime, *, clear_lease: bool) -> None: ...
    def enqueue(self, run_id: UUID, message_type: str, at: datetime) -> None: ...
    def complete_pending(self, run_id: UUID, at: datetime) -> None: ...
    def has_pending(self, run_id: UUID, message_type: str) -> bool: ...
    def requeue_execute(self, run_id: UUID, at: datetime) -> None: ...


class RunMessageRepository(Protocol):
    def initial(self, run: Run, content: str, at: datetime) -> None: ...
    def user_input(self, run: Run, content: str) -> None: ...


class RunInputRepository(Protocol):
    def get(self, request_id: UUID) -> PendingInput | None: ...
    def consume(self, request_id: UUID, response: str, key: str, at: datetime) -> None: ...


class RunAuditRepository(Protocol):
    def write(self, tenant_id: UUID, user_id: UUID, action: str,
              resource_type: str, resource_id: str, details: dict[str, Any] | None = None) -> None: ...


class RunCommandUnitOfWork(RunUnitOfWork, Protocol):
    """One write transaction with configuration, permissions, event, message and queue adapters."""
    runs: RunWriteRepository
    access: SubmissionAccess
    outbox: RunQueueRepository
    catalog: SubmissionCatalog
    messages: RunMessageRepository
    inputs: RunInputRepository
    audit: RunAuditRepository

    def __enter__(self) -> 'RunCommandUnitOfWork': ...
